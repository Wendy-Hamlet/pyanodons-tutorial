// Copies the entities inside a tile area of a save snapshot (entities.json from
// tools/inspect-save.ps1) into tools/design-lab/extracted.lua, so the design lab can rebuild the
// structure on a clean map and measure it. Coordinates are stored relative to the area's corner.
// Usage: node tools/extract-design.js <key> x1 y1 x2 y2   (inclusive tile range)

const fs = require('fs');
const path = require('path');

const [key, ...nums] = process.argv.slice(2);
const [x1, y1, x2, y2] = nums.map(Number);
const all = require(`${require('./paths').save}/entities.json`);
const file = path.join(__dirname, 'design-lab', 'extracted.lua');

const inside = (e) => e.x >= x1 && e.x < x2 + 1 && e.y >= y1 && e.y < y2 + 1;
const picked = all.filter((e) => inside(e) && e.type !== 'entity-ghost');
const lua = (v) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
const lines = picked.map((e) => {
  const fields = [`name = ${lua(e.name)}`, `x = ${e.x - x1}`, `y = ${e.y - y1}`];
  if (e.dir) fields.push(`dir = ${lua(e.dir)}`);
  if (e.ug) fields.push(`ug = ${lua(e.ug)}`);
  if (e.filter) fields.push(`filter = ${lua(e.filter)}`);
  return `    { ${fields.join(', ')} },`;
});
const block = `  [${lua(key)}] = { width = ${x2 - x1 + 1}, height = ${y2 - y1 + 1}, entities = {\n${lines.join('\n')}\n  } },\n`;

let designs = {};
if (fs.existsSync(file)) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/^  \["([^"]+)"\] = [\s\S]*?^  } },\n/gm)) designs[m[1]] = m[0];
}
designs[key] = block;
const header = '-- Generated by tools/extract-design.js from save snapshots; do not edit by hand.\nreturn {\n';
fs.writeFileSync(file, header + Object.values(designs).join('') + '}\n');
const counts = {};
for (const e of picked) counts[e.name] = (counts[e.name] || 0) + 1;
console.log(`${key}: ${picked.length} entities (${Object.entries(counts).map(([n, c]) => `${n}×${c}`).join(', ')})`);
