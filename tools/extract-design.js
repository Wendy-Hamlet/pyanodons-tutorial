// Copies a structure into tools/design-lab/extracted.lua, so the design lab can rebuild it on a
// clean map and measure it: either the entities inside a tile area of a save snapshot
// (entities.json from tools/inspect-save.ps1), or a whole blueprint file. Coordinates are stored
// relative to the area's corner.
// Usage: node tools/extract-design.js <key> x1 y1 x2 y2   (inclusive tile range of the snapshot)
//        node tools/extract-design.js <key> --blueprint blueprints/<name>.txt

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const [key, ...rest] = process.argv.slice(2);
const file = path.join(__dirname, 'design-lab', 'extracted.lua');

// Blueprint entities in the snapshot's format (centre x/y, dir, ug, filter). Sizes of the
// entities used so far; everything else is 1x1.
const SIZE = { 'burner-mining-drill': 2, 'stone-furnace': 2 };
const DIR = { 0: 'north', 4: 'east', 8: 'south', 12: 'west' };
function fromBlueprint(bpFile) {
  const text = fs.readFileSync(bpFile, 'utf8').trim();
  const bp = JSON.parse(zlib.inflateSync(Buffer.from(text.slice(1), 'base64')).toString('utf8')).blueprint;
  return bp.entities.map((e) => ({
    name: e.name, x: e.position.x, y: e.position.y, size: SIZE[e.name] || 1,
    dir: e.direction !== undefined ? DIR[e.direction] : (e.name.includes('belt') ? 'north' : undefined),
    ug: e.type, filter: e.use_filters && e.filters ? e.filters[0].name : undefined,
    filter_mode: e.filter_mode,
  }));
}

let picked, x1, y1, x2, y2;
if (rest[0] === '--blueprint') {
  picked = fromBlueprint(rest[1]);
  x1 = Math.min(...picked.map((e) => Math.floor(e.x - e.size / 2)));
  y1 = Math.min(...picked.map((e) => Math.floor(e.y - e.size / 2)));
  x2 = Math.max(...picked.map((e) => Math.ceil(e.x + e.size / 2) - 1));
  y2 = Math.max(...picked.map((e) => Math.ceil(e.y + e.size / 2) - 1));
} else {
  [x1, y1, x2, y2] = rest.map(Number);
  const all = require(`${require('./paths').save}/entities.json`);
  const inside = (e) => e.x >= x1 && e.x < x2 + 1 && e.y >= y1 && e.y < y2 + 1;
  picked = all.filter((e) => inside(e) && e.type !== 'entity-ghost');
}
const lua = (v) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
const lines = picked.map((e) => {
  const fields = [`name = ${lua(e.name)}`, `x = ${e.x - x1}`, `y = ${e.y - y1}`];
  if (e.dir) fields.push(`dir = ${lua(e.dir)}`);
  if (e.ug) fields.push(`ug = ${lua(e.ug)}`);
  if (e.filter) fields.push(`filter = ${lua(e.filter)}`);
  if (e.filter_mode === 'blacklist') fields.push('mode = "blacklist"');
  return `    { ${fields.join(', ')} },`;
});
const block = `  [${lua(key)}] = { width = ${x2 - x1 + 1}, height = ${y2 - y1 + 1}, entities = {\n${lines.join('\n')}\n  } },\n`;

let designs = {};
if (fs.existsSync(file)) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/^  \["([^"]+)"\] = [\s\S]*?^  } },\n/gm)) designs[m[1]] = m[0];
}
designs[key] = block;
const header = '-- Generated by tools/extract-design.js from save snapshots and blueprints; do not edit by hand.\nreturn {\n';
fs.writeFileSync(file, header + Object.values(designs).join('') + '}\n');
const counts = {};
for (const e of picked) counts[e.name] = (counts[e.name] || 0) + 1;
console.log(`${key}: ${picked.length} entities (${Object.entries(counts).map(([n, c]) => `${n}×${c}`).join(', ')})`);
