// Keeps blueprints/ and the game in sync, together with the companion mod (tools/companion).
//
//   node tools/bp-sync.js push
//     Builds one blueprint book from blueprints/*.txt (order from blueprints/book.json, unlisted
//     files appended) and writes it to blueprints/book.txt (one string for readers to import) and
//     tools/companion/book.lua (what the companion mod puts into your cursor).
//
//   node tools/bp-sync.js pull [--dry] [export-file]
//     Reads a book or blueprint exported in game with the companion mod (default:
//     %APPDATA%\Factorio\script-output\py-tutorial-companion\export.txt). Blueprints are matched to
//     files by label and compared after decoding, so only real changes are written; unknown labels
//     become new files. Files missing from the export are reported, never deleted. Then pushes.

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const dir = path.join(__dirname, '..', 'blueprints');
const manifestFile = path.join(dir, 'book.json');
const bookLua = path.join(__dirname, 'companion', 'book.lua');
const defaultExport = path.join(process.env.APPDATA || '', 'Factorio', 'script-output',
  'py-tutorial-companion', 'export.txt');

const decode = (s) => JSON.parse(zlib.inflateSync(Buffer.from(s.trim().slice(1), 'base64')).toString('utf8'));
const encode = (obj) => '0' + zlib.deflateSync(Buffer.from(JSON.stringify(obj), 'utf8'), { level: 9 }).toString('base64');

// Key-sorted JSON without the game version, so two exports of the same design compare equal.
const canonical = (v) => {
  if (Array.isArray(v)) return `[${v.map(canonical).join(',')}]`;
  if (v && typeof v === 'object') {
    return `{${Object.keys(v).filter((k) => k !== 'version').sort()
      .map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`).join(',')}}`;
  }
  return JSON.stringify(v);
};

const readManifest = () => JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
const fileNames = () => fs.readdirSync(dir)
  .filter((f) => f.endsWith('.txt') && f !== 'book.txt').map((f) => f.slice(0, -4)).sort();
const readPrint = (name) => decode(fs.readFileSync(path.join(dir, `${name}.txt`), 'utf8'));
const labelOf = (entry) => (entry.blueprint || entry.blueprint_book || {}).label;

function push() {
  const manifest = readManifest();
  const present = fileNames();
  const missing = manifest.blueprints.filter((n) => !present.includes(n));
  if (missing.length) throw new Error(`book.json lists files that do not exist: ${missing.join(', ')}`);
  const names = [...manifest.blueprints, ...present.filter((n) => !manifest.blueprints.includes(n))];
  const entries = names.map(readPrint);
  const version = Object.values(entries[0])[0].version;
  const book = {
    blueprint_book: {
      item: 'blueprint-book',
      label: manifest.label,
      description: manifest.description,
      blueprints: entries.map((e, index) => ({ index, ...e })),
      active_index: 0,
      version,
    },
  };
  const text = encode(book);
  fs.writeFileSync(path.join(dir, 'book.txt'), `${text}\n`);
  const now = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  const stamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}`;
  fs.writeFileSync(bookLua, '-- Generated by tools/bp-sync.js push from blueprints/; do not edit by hand.\n'
    + `return {\n  generated = ${JSON.stringify(stamp)},\n  count = ${names.length},\n`
    + `  string = ${JSON.stringify(text)},\n}\n`);
  console.log(`push: book "${manifest.label}" with ${names.length} blueprints -> blueprints/book.txt, tools/companion/book.lua`);
  names.forEach((n, i) => console.log(`  ${i + 1}. ${n}: ${labelOf(entries[i])}`));
}

// Flattens an exported book (nested books included) into its blueprints, in book order.
function collect(obj, out) {
  if (obj.blueprint) out.push({ blueprint: obj.blueprint });
  else if (obj.blueprint_book) {
    const children = [...(obj.blueprint_book.blueprints || [])].sort((a, b) => a.index - b.index);
    for (const child of children) collect(child, out);
  } else console.log(`  skipped a ${Object.keys(obj).filter((k) => k !== 'index').join('/')} (not a blueprint)`);
  return out;
}

const slug = (label) => (label || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

function pull(file, dry) {
  console.log(`pull: ${file} (exported ${fs.statSync(file).mtime.toLocaleString()})`);
  const incoming = collect(decode(fs.readFileSync(file, 'utf8')), []);
  const byLabel = new Map();
  for (const name of fileNames()) byLabel.set(labelOf(readPrint(name)), name);
  const taken = new Set(fileNames());
  const order = [];
  const writes = [];
  incoming.forEach((entry, i) => {
    const label = labelOf(entry);
    let name = label !== undefined ? byLabel.get(label) : undefined;
    if (name !== undefined) {
      byLabel.delete(label);
      const same = canonical(readPrint(name)) === canonical(entry);
      console.log(`  ${same ? 'unchanged' : 'CHANGED  '} ${name} (${label})`);
      if (!same) writes.push([name, entry]);
    } else {
      const base = slug(label) || `blueprint-${i + 1}`;
      name = base;
      for (let n = 2; taken.has(name); n += 1) name = `${base}-${n}`;
      console.log(`  NEW       ${name} (${label === undefined ? 'no label' : label})`);
      writes.push([name, entry]);
    }
    taken.add(name);
    order.push(name);
  });
  for (const [label, name] of byLabel) console.log(`  missing   ${name} (${label}) - not in the export, file kept`);
  if (dry) return;
  for (const [name, entry] of writes) fs.writeFileSync(path.join(dir, `${name}.txt`), `${encode(entry)}\n`);
  const manifest = readManifest();
  manifest.blueprints = [...order, ...manifest.blueprints.filter((n) => !order.includes(n))];
  fs.writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`pull: wrote ${writes.length} file(s); designs that changed need re-measuring in tools/design-lab`);
  push();
}

const [command, ...rest] = process.argv.slice(2);
if (command === 'push') push();
else if (command === 'pull') {
  const dry = rest.includes('--dry');
  pull(rest.find((a) => a !== '--dry') || defaultExport, dry);
} else {
  console.log('usage: node tools/bp-sync.js push | pull [--dry] [export-file]');
  process.exit(1);
}
